CREATE TABLE privilegio (
    codigo VARCHAR2(80) PRIMARY KEY,
    descripcion VARCHAR2(200) NOT NULL
);

CREATE TABLE rol (
    codigo VARCHAR2(40) PRIMARY KEY,
    descripcion VARCHAR2(120) NOT NULL
);

CREATE TABLE rol_privilegio (
    rol_codigo VARCHAR2(40) NOT NULL,
    privilegio_codigo VARCHAR2(80) NOT NULL,
    CONSTRAINT pk_rol_privilegio PRIMARY KEY (rol_codigo, privilegio_codigo),
    CONSTRAINT fk_rp_rol FOREIGN KEY (rol_codigo) REFERENCES rol(codigo),
    CONSTRAINT fk_rp_priv FOREIGN KEY (privilegio_codigo) REFERENCES privilegio(codigo)
);

CREATE TABLE usuario (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(80) NOT NULL UNIQUE,
    password_hash VARCHAR2(100) NOT NULL,
    rol_codigo VARCHAR2(40) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_codigo) REFERENCES rol(codigo)
);

CREATE TABLE lote (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(30) NOT NULL UNIQUE,
    nombre VARCHAR2(120) NOT NULL,
    hectareas NUMBER(10,2) NOT NULL,
    cultivo VARCHAR2(80) NOT NULL,
    valle VARCHAR2(80) NOT NULL,
    campania_cerrada NUMBER(1) DEFAULT 0 NOT NULL,
    dosis_maxima NUMBER(10,3) NOT NULL,
    CONSTRAINT ck_lote_hectareas CHECK (hectareas > 0),
    CONSTRAINT ck_lote_dosis CHECK (dosis_maxima >= 0)
);

CREATE TABLE labor (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id NUMBER NOT NULL,
    tipo VARCHAR2(20) NOT NULL,
    fecha DATE NOT NULL,
    responsable_id NUMBER NOT NULL,
    cantidad NUMBER(12,3) NOT NULL,
    observacion VARCHAR2(500) NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_labor_lote FOREIGN KEY (lote_id) REFERENCES lote(id),
    CONSTRAINT fk_labor_usuario FOREIGN KEY (responsable_id) REFERENCES usuario(id),
    CONSTRAINT ck_labor_tipo CHECK (tipo IN ('RIEGO','FUMIGACION','COSECHA')),
    CONSTRAINT ck_labor_cantidad CHECK (cantidad > 0)
);

CREATE INDEX ix_labor_lote_fecha ON labor(lote_id, fecha DESC);
